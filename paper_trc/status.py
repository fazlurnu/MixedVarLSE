"""Write STATUS.md from results/*/*/run.json. Never edit STATUS.md by hand.

    python status.py
"""

import json
from pathlib import Path

import config

HERE = Path(__file__).resolve().parent
PLANNED = {
    "exp0_verify": ["active"],
    "exp1_heading": ["bracket", "campaign"],
    "exp2_surface": [f"dpsi{d:.0f}_{k}" for d in config.EXPERIMENTS["exp2_surface"]["headings"]
                     for k in ("bracket", "campaign")]
                    + [f"dpsi{d:.0f}_{s}_{k}" for d, s in config.EXPERIMENTS["exp2_surface"]["extra_runs"]
                       for k in ("bracket", "campaign")],
    "exp3_margin": ["dpsi180_margin1.05"],
    "exp4_confirm": ["boundary"],
}


def row(experiment: str, tag: str) -> str:
    manifest_path = HERE / "results" / experiment / tag / "run.json"
    if not manifest_path.exists():
        return f"| {experiment} | {tag} | not run | | | | |"
    m = json.loads(manifest_path.read_text())
    out = m.get("outcome") or {}
    status = m["status"] if m["status"] == "done" else "interrupted or running"
    if any(s["dirty"] for s in m["code"].values()):
        status += " ⚠ dirty code"
    commit = m["code"]["mvlse"]["commit"][:7] + " / " + m["code"]["blueskycdarr"]["commit"][:7]
    n = out.get("n_evaluations", "")
    stop = out.get("stop_reason", "")
    if out.get("final_max_straddle") is not None:
        stop += f" (max straddle {out['final_max_straddle']:+.3f})"
    return (f"| {experiment} | {tag} | {status} | {m['started']} | {n} | {stop} | {commit} |")


def main() -> None:
    lines = [
        "# Experiment status",
        "",
        "Generated by `python status.py` from each run's `run.json`. Do not edit by hand.",
        "",
        "| experiment | run | status | started | evaluations | stop | commit (mvlse / bluesky) |",
        "|---|---|---|---|---|---|---|",
    ]
    lines += [row(e, t) for e, tags in PLANNED.items() for t in tags]
    (HERE / "STATUS.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
