"""Write the paper's parameter tables from config.py, so the text cannot drift from the runs.

    python make_tables.py   ->  tables/fixed_parameters.tex, tables/design_variables.tex

The journal \\input's these files; edit config.py, never the .tex.
"""

from pathlib import Path

from mvlse import Continuous

import config

HERE = Path(__file__).resolve().parent
OUT = HERE / "tables"
HEADER = "% GENERATED by paper_trc/make_tables.py from config.py -- do not edit.\n"


def fixed_parameters() -> str:
    f = config.FIXED
    rows = [
        ("Protected-zone radius", r"$R_\mathrm{PZ}$", f"{f['rpz']:g}~m"),
        ("Projected miss distance at spawn", r"$d_\mathrm{CPA}$", f"{f['dcpa']:g}~m"),
        ("Time to loss of separation at spawn", r"$t_\mathrm{LoS}$", f"{f['tlos']:g}~s"),
        ("Look-ahead time", r"$t_\mathrm{lookahead}$", f"{f['t_lookahead']:g}~s"),
        ("Resolution margin", "--", f"{f['resolution_margin']:.2f}"),
        ("Broadcast rate", "--", "1~Hz"),
        ("Maximum turn rate", r"$\omega_\mathrm{max}$", f"{config.MAX_TURN_RATE:g}~deg/s"),
        ("Maximum turn-rate change", r"$\dot\omega_\mathrm{max}$",
         f"{config.MAX_TURN_ACCEL:g}~deg/s$^2$"),
        ("Encounters per sample", "$N$", f"{config.N_ENCOUNTERS:,}".replace(",", "{,}")),
        ("Threshold", r"$\tau$", rf"$10^{{{config.TAU:g}}}$"),
        ("Resolution", "--", config.RESOLVER),
        ("Recovery", "--", "Probabilistic FTR"),
    ]
    body = "\n".join(f"{a} & {b} & {c} \\\\" for a, b, c in rows)
    return (HEADER + "\\begin{tabular}{lll}\n\\hline\nParameter & Symbol & Value \\\\\n\\hline\n"
            + body + "\n\\hline\n\\end{tabular}\n")


def design_variables() -> str:
    names = {
        "p_reception": ("Reception probability", r"$p_\mathrm{rec}$", ""),
        "max_range_m": ("Surveillance range", r"$R_\mathrm{surv}$", "m"),
        "pos_ci95": ("Position accuracy (95\\%)", r"$\ell_p$", "m"),
        "vel_ci95": ("Velocity accuracy (95\\%)", r"$\ell_v$", "m/s"),
    }
    rows = []
    for key, var in config.CNS_VARIABLES.items():
        label, sym, unit = names[key]
        unit = f"~{unit}" if unit else ""
        if isinstance(var, Continuous):
            rows.append((label, sym, "continuous", f"{var.lower:g}--{var.upper:g}{unit}"))
        else:
            rows.append((label, sym, "ordinal", "\\{" + ", ".join(f"{v:g}" for v in var.levels)
                         + "\\}" + unit))
    lo, hi = config.HEADING_RANGE
    rows.append(("Relative heading", r"$\theta$", "continuous",
                 f"{lo:g}--{hi:g}\\textdegree{{}} (Exp.~1); 2, 180\\textdegree{{}} (Exp.~2)"))
    speeds = ", ".join(f"{k.replace('kt', '~kt')} ({v:.1f}~m/s)"
                       for k, v in config.SPEED_CLASSES.items())
    rows.append(("Aircraft performance category", "$k$", "ordinal",
                 f"{speeds} (Exp.~1); 20~kt (Exp.~2)"))
    body = "\n".join(" & ".join(r) + " \\\\" for r in rows)
    return (HEADER + "\\begin{tabular}{llll}\n\\hline\nVariable & Symbol & Type & Range or levels"
            " \\\\\n\\hline\n" + body + "\n\\hline\n\\end{tabular}\n")


if __name__ == "__main__":
    OUT.mkdir(exist_ok=True)
    (OUT / "fixed_parameters.tex").write_text(fixed_parameters())
    (OUT / "design_variables.tex").write_text(design_variables())
    print(f"wrote {OUT / 'fixed_parameters.tex'} and {OUT / 'design_variables.tex'}")
